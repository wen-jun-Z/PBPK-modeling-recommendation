"""Extract a checksum-bound human physiology *design input*, never a PKML model.

PK-Sim JSON snapshots usually store individual generation recipes, not a complete
anatomical model. Consequently callers must supply an independently traceable
compartment manifest; output selections and drug processes never define anatomy.
Only OriginData.Age/Weight and explicitly serialized individual organ volumes or
blood flows are supported. Height is intentionally not exported: the existing
ParameterDimension contract has no length dimension. No physiological values,
units, organ connections, healthy-adult designation, or executable status are
inferred. Sparse source values remain missing, rather than regenerated by PK-Sim.

A source population describes this imported individual, not general population
qualification. Explicit supported_populations are caller-reviewed scope metadata;
this adapter does not validate clinical applicability. An organ parameter copied
from an individual remains an inherited model value, not clinical evidence. Drug
Kp, binding fractions, clearance, expression profiles, dosing, simulations and
results are never traversed or inherited.
"""
from __future__ import annotations

import hashlib
import json
import math
import re
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any
from uuid import NAMESPACE_URL, uuid5

from pbpk_kb.blueprints.design_contracts import HumanPhysiologyBase
from pbpk_kb.blueprints.schemas import (
    CompartmentDefinition,
    DerivedParameter,
    MissingParameter,
    ParameterContext,
    ParameterDefinition,
    ProvenanceRef,
)

PHYSIOLOGY_ADAPTER_VERSION = "human-snapshot-physiology-1.0.0"
_MAX_SOURCE_BYTES = 16 * 1024 * 1024
_CHECKSUM = re.compile(r"[0-9a-f]{64}\Z")

# Positive allowlists, deliberately narrower than arbitrary Individual.Parameters.
_ANATOMY = {
    "organism", "arterialblood", "venousblood", "peripheralvenousblood",
    "portalvein", "portalblood", "blood", "plasma", "bloodcells",
    "redbloodcells", "interstitial", "intracellular", "extracellular",
    "liver", "kidney", "kidneys", "lung", "lungs", "heart", "brain",
    "muscle", "skin", "bone", "pancreas", "spleen", "gonads", "fat",
    "adipose", "adiposetissue", "stomach", "smallintestine", "largeintestine",
    "duodenum", "jejunum", "ileum", "caecum", "cecum", "colon", "rectum",
    "gallbladder", "urine", "bile", "lumen", "mucosa", "endothelium",
}
_UNITS = {
    "time": {"year(s)", "year", "years", "month(s)", "month", "months",
             "week(s)", "week", "weeks", "day(s)", "day", "days", "h", "min"},
    "mass": {"kg", "g", "mg"},
    "volume": {"l", "L", "ml", "mL", "ul", "uL", "µl", "µL", "μl", "μL"},
    "flow": {"l/min", "L/min", "ml/min", "mL/min", "l/h", "L/h",
             "ml/h", "mL/h", "ul/min", "µl/min", "μl/min"},
}
_ORGAN_PARAMETERS = {"volume": "volume", "bloodflow": "flow", "bloodflowrate": "flow"}


class HumanPhysiologyExtractionError(ValueError):
    """The source cannot be represented without guessing or losing provenance."""


def _key(value: str) -> str:
    return re.sub(r"[^a-z0-9]", "", value.casefold())


def _provenance(path: str, checksum: str, pointer: str) -> ProvenanceRef:
    location = f"{path}#{pointer}"
    return ProvenanceRef(
        provenance_id=uuid5(NAMESPACE_URL, f"{location}\n{checksum}"),
        provenance_kind="model_asset", source_id=path,
        source_location=location, source_checksum=checksum,
    )


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise HumanPhysiologyExtractionError(f"DUPLICATE_SNAPSHOT_KEY: {key}")
        result[key] = value
    return result


def _reject_constant(value: str) -> None:
    raise HumanPhysiologyExtractionError(f"NONFINITE_SNAPSHOT_VALUE: {value}")


def _verify_source(snapshot: dict, path: str, checksum: str, raw: bytes | None) -> None:
    if not path.strip() or not _CHECKSUM.fullmatch(checksum):
        raise HumanPhysiologyExtractionError("SOURCE_PATH_AND_SHA256_REQUIRED")
    if raw is None:
        # File ownership/boundary policy belongs to the calling CLI/API. No path
        # discovery, runtime execution, or external resource resolution occurs.
        with Path(path).open("rb") as handle:
            raw = handle.read(_MAX_SOURCE_BYTES + 1)
    if not isinstance(raw, bytes) or len(raw) > _MAX_SOURCE_BYTES:
        raise HumanPhysiologyExtractionError("SOURCE_BYTES_INVALID_OR_TOO_LARGE")
    if hashlib.sha256(raw).hexdigest() != checksum:
        raise HumanPhysiologyExtractionError("SOURCE_CHECKSUM_MISMATCH")
    try:
        original = json.loads(raw, object_pairs_hook=_unique_object,
                              parse_constant=_reject_constant)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise HumanPhysiologyExtractionError("SOURCE_IS_NOT_JSON") from exc
    if not isinstance(original, dict) or original != snapshot:
        raise HumanPhysiologyExtractionError("SNAPSHOT_DOES_NOT_MATCH_SOURCE_BYTES")


def _compartments(
    manifest: Sequence[CompartmentDefinition | Mapping[str, Any]] | None,
) -> tuple[list[CompartmentDefinition], dict[tuple[str, ...], str]]:
    if not manifest:
        raise HumanPhysiologyExtractionError("EXPLICIT_SOURCED_COMPARTMENT_MANIFEST_REQUIRED")
    result = [CompartmentDefinition.model_validate(x).model_copy(deep=True) for x in manifest]
    by_id = {x.compartment_id: x for x in result}
    if len(by_id) != len(result):
        raise HumanPhysiologyExtractionError("DUPLICATE_PHYSIOLOGY_COMPARTMENT")
    paths: dict[tuple[str, ...], str] = {}
    for item in result:
        if _key(item.name) not in _ANATOMY or item.compartment_type == "sink":
            raise HumanPhysiologyExtractionError(f"UNSUPPORTED_BASE_ANATOMY: {item.name}")
        names, seen = [], set()
        current = item
        while True:
            if current.compartment_id in seen:
                raise HumanPhysiologyExtractionError("CYCLIC_COMPARTMENT_HIERARCHY")
            seen.add(current.compartment_id)
            names.append(_key(current.name))
            parent = current.parent_compartment_id
            if parent is None:
                break
            if parent not in by_id:
                raise HumanPhysiologyExtractionError("UNRESOLVED_COMPARTMENT_PARENT")
            current = by_id[parent]
        path = tuple(reversed(names))
        if path[0] != "organism":
            raise HumanPhysiologyExtractionError("EXPLICIT_ORGANISM_ROOT_REQUIRED")
        if path in paths:
            raise HumanPhysiologyExtractionError("AMBIGUOUS_ANATOMICAL_PATH")
        paths[path] = item.compartment_id
    return result, paths


def _parameter(
    *, name: str, dimension: str, row: dict | None, model_path: str,
    context: ParameterContext, provenance: ProvenanceRef,
) -> ParameterDefinition:
    identity = uuid5(NAMESPACE_URL, f"{provenance.provenance_id}|{model_path}").hex
    common = dict(
        parameter_id=f"physiology-{identity}",
        semantic_id=(f"physiology:{_key(name)}" if "|OriginData|" in model_path
                     else "physiology:" + ":".join(_key(x) for x in model_path.split("|"))),
        name=name, model_path=model_path, dimension=dimension,
        context=context, provenance=[provenance],
    )
    if row is None:
        return MissingParameter(
            **common, origin="missing", blocking=True,
            missing_reason_code="PHYSIOLOGY_VALUE_NOT_SERIALIZED",
        )
    value, unit = row.get("Value"), row.get("Unit")
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise HumanPhysiologyExtractionError(f"EXPLICIT_FINITE_VALUE_REQUIRED: {model_path}")
    if value < 0 or (dimension in {"mass", "volume"} and value == 0):
        raise HumanPhysiologyExtractionError(f"INVALID_PHYSIOLOGY_VALUE: {model_path}")
    if not isinstance(unit, str) or unit not in _UNITS[dimension]:
        raise HumanPhysiologyExtractionError(f"EXPLICIT_SUPPORTED_UNIT_REQUIRED: {model_path}")
    return DerivedParameter(
        **common, origin="derived", value=float(value), canonical_unit=unit,
        blocking=False, derivation_expression=f"inherit_template_value:{provenance.source_location}",
        expression_version=PHYSIOLOGY_ADAPTER_VERSION,
    )


def from_snapshot(
    snapshot: dict,
    *,
    individual_name: str,
    source_path: str | Path,
    source_checksum: str,
    base_id: str,
    version: str,
    compartment_manifest: Sequence[CompartmentDefinition | Mapping[str, Any]] | None = None,
    supported_populations: Sequence[str] | None = None,
    source_bytes: bytes | None = None,
) -> HumanPhysiologyBase:
    """Import one explicitly selected Human individual, without invoking PK-Sim.

    ``source_bytes`` binds an in-memory snapshot to original JSON bytes; otherwise
    only ``source_path`` is read (at most 16 MiB). The caller must enforce permitted
    filesystem scope before invoking the file-reading form. The checksum covers
    original bytes, not reserialized JSON. Compartment provenance is retained from
    the caller's manifest; its artifacts are not loaded or silently manufactured.

    The manifest must explicitly contain Organism and parent links. Recognized
    volume/flow paths absent from that manifest raise an error. Unsupported fields
    (including Height, enzyme abundances, EHC, Kp, fu and clearance) are intentionally
    excluded by a positive whitelist. Absent Age/Weight become blocking missing
    parameters. Sparse snapshots do not establish complete organ parameterization
    or blood-flow connectivity, and the returned base is not executable PKML.
    """
    path = str(source_path)
    _verify_source(snapshot, path, source_checksum, source_bytes)
    if isinstance(snapshot.get("Version"), bool) or not isinstance(snapshot.get("Version"), int):
        raise HumanPhysiologyExtractionError("PKSIM_SNAPSHOT_VERSION_REQUIRED")
    individuals = snapshot.get("Individuals")
    if not isinstance(individuals, list) or any(not isinstance(x, dict) for x in individuals):
        raise HumanPhysiologyExtractionError("INVALID_INDIVIDUAL_COLLECTION")
    matches = [(i, x) for i, x in enumerate(individuals) if x.get("Name") == individual_name]
    if len(matches) != 1:
        raise HumanPhysiologyExtractionError("ONE_EXPLICIT_INDIVIDUAL_REQUIRED")
    index, individual = matches[0]
    origin = individual.get("OriginData")
    if not isinstance(origin, dict) or origin.get("Species") != "Human":
        raise HumanPhysiologyExtractionError("EXPLICIT_HUMAN_SPECIES_REQUIRED")
    population = origin.get("Population")
    if population is not None and (not isinstance(population, str) or not population.strip()):
        raise HumanPhysiologyExtractionError("INVALID_SOURCE_POPULATION")
    if supported_populations is None:
        populations = [population] if population is not None else []
    else:
        if isinstance(supported_populations, (str, bytes)):
            raise HumanPhysiologyExtractionError("POPULATION_LIST_REQUIRED")
        populations = list(supported_populations)
        if any(not isinstance(x, str) or not x.strip() for x in populations) or len(set(populations)) != len(populations):
            raise HumanPhysiologyExtractionError("EXPLICIT_UNIQUE_POPULATIONS_REQUIRED")
    if not populations:
        raise HumanPhysiologyExtractionError("EXPLICIT_POPULATION_SCOPE_REQUIRED")
    if population is not None and population not in populations:
        raise HumanPhysiologyExtractionError("SOURCE_POPULATION_MUST_REMAIN_IN_SCOPE")
    compartments, anatomical_paths = _compartments(compartment_manifest)
    root_id = anatomical_paths[("organism",)]
    pointer = f"/Individuals/{index}"
    context = ParameterContext(species="Human", population=population, compartment_id=root_id)
    parameters: list[ParameterDefinition] = []
    for name, dimension in (("Age", "time"), ("Weight", "mass")):
        row = origin.get(name)
        if name in origin and not isinstance(row, dict):
            raise HumanPhysiologyExtractionError(f"INVALID_PHYSIOLOGY_FIELD: {name}")
        parameters.append(_parameter(
            name=name, dimension=dimension, row=row,
            model_path=f"Individuals|{individual_name}|OriginData|{name}", context=context,
            provenance=_provenance(
                path, source_checksum,
                f"{pointer}/OriginData/{name}" if row is not None else f"{pointer}/OriginData",
            ),
        ))
    rows = individual.get("Parameters", [])
    if not isinstance(rows, list) or any(not isinstance(x, dict) for x in rows):
        raise HumanPhysiologyExtractionError("INVALID_INDIVIDUAL_PARAMETERS")
    seen_paths: set[tuple[str, ...]] = set()
    for position, row in enumerate(rows):
        model_path = row.get("Path")
        if not isinstance(model_path, str):
            continue
        parts = tuple(_key(x) for x in model_path.split("|"))
        if len(parts) < 3 or parts[0] != "organism" or parts[-1] not in _ORGAN_PARAMETERS:
            continue
        # Exact anatomical parents prevent a compound's similarly named value
        # from being imported through a nested drug scope.
        if any(part not in _ANATOMY for part in parts[:-1]):
            continue
        if parts[:-1] not in anatomical_paths:
            raise HumanPhysiologyExtractionError(f"PHYSIOLOGY_PATH_NOT_IN_MANIFEST: {model_path}")
        if parts in seen_paths:
            raise HumanPhysiologyExtractionError(f"DUPLICATE_PHYSIOLOGY_PATH: {model_path}")
        seen_paths.add(parts)
        parameters.append(_parameter(
            name=model_path.split("|")[-1], dimension=_ORGAN_PARAMETERS[parts[-1]],
            row=row, model_path=model_path,
            context=ParameterContext(species="Human", population=population,
                                     compartment_id=anatomical_paths[parts[:-1]]),
            provenance=_provenance(path, source_checksum, f"{pointer}/Parameters/{position}"),
        ))
    provenance = [_provenance(path, source_checksum, pointer)]
    by_provenance_id = {x.provenance_id: x for x in provenance}
    for item in [*compartments, *parameters]:
        for ref in item.provenance:
            previous = by_provenance_id.get(ref.provenance_id)
            if previous is not None and previous != ref:
                raise HumanPhysiologyExtractionError("CONFLICTING_PROVENANCE_ID")
            by_provenance_id[ref.provenance_id] = ref
    return HumanPhysiologyBase(
        base_id=base_id, version=version, compartments=compartments,
        parameters=parameters, supported_populations=populations,
        provenance=list(by_provenance_id.values()),
    )
