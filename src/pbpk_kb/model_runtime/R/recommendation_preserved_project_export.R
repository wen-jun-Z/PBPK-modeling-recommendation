# Export a selected saved model from an isolated project with no observations
# or old simulation results. Never rebuild from a JSON snapshot or solve ODEs.
args <- commandArgs(trailingOnly=TRUE)
if (length(args)!=3L) stop("Expected isolated model-only project, simulation name, output directory")
suppressPackageStartupMessages(library(ospsuite))
input <- normalizePath(args[[1]],mustWork=TRUE)
output <- normalizePath(args[[3]],mustWork=TRUE)
if (length(list.files(output,all.files=TRUE,no..=TRUE))) stop("Export directory must be empty")
ospsuite::initPKSim()
opts <- rSharp::newObjectFromName("PKSim.CLI.Core.RunOptions.ExportRunOptions")
names <- rSharp::newObjectFromName("System.Collections.Generic.List`1[System.String]")
names$call("Add",args[[2]])
opts$set("ProjectFile",input)
opts$set("OutputFolder",output)
opts$set("Simulations",names)
opts$set("ExportAllSimulationsIfListIsEmpty",FALSE)
opts$set("RunSimulation",FALSE)
opts$set("ExportMode",8L)
rSharp::callStatic("PKSim.R.Api","RunSimulationExport",opts)
files <- list.files(output,pattern="\\.pkml$",recursive=TRUE,full.names=TRUE)
if (length(files)!=1L) stop("Exactly one preserved model PKML must be exported")
cat("PRESERVED_PROJECT_PKML_EXPORTED_WITHOUT_ODE\n")
