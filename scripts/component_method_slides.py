"""Introductory component recommendation: two main slides and two backups."""
from presentation_teaching_common import *


def make_component_slides():
    pages = []
    s = teaching_slide(
        '组件推荐：先决定模型里需要哪些过程',
        '组件是模型的一部分；把这些部分正确组合，才可能计算药物浓度。',
        '组件推荐 / 是什么')
    card(s, 64, 151, 492, 67, '药物 X：静脉输注后，预测血浆浓度')
    arrow(s, (310, 222), (310, 239))
    s.line([(130, 242), (490, 242)], TEAL, 1.3)
    for x, title, body, color, fill in [
        (50, '输入', '输注时\n药物进入人体', TEAL, PALE),
        (230, '分布', '蛋白结合等\n影响药物分布', GREEN, GREEN_PALE),
        (410, '清除', '药物被代谢\n或排出人体', GOLD, GOLD_PALE),
    ]:
        arrow(s, (x+80, 242), (x+80, 256), color)
        card(s, x, 261, 160, 103, title, body, color, fill)
    example(s, '这是组件含义的示例；真正推荐哪些过程，要检查药物证据和用户用途。')
    words(s, [
        ('“组件”是什么意思', '可以把它理解为模型里的一个过程，例如药物怎样进入、怎样分布、怎样被清除。'),
        ('这一步交付什么', '给出建议加入的过程、支持资料和缺口；还没有生成一条预测浓度曲线。'),
    ], '组件推荐先回答“模型里该考虑什么”，完整模型再回答“浓度是多少”。')
    pages.append(s)

    s = teaching_slide(
        '怎么推荐：找证据，再核对它能不能用于当前问题',
        '同一篇资料可能与药物有关，但不一定支持当前的人群、给药方式和预测目标。',
        '组件推荐 / 怎么做')
    card(s, 54, 157, 226, 96, '① 找资料', '药名与关键词\n＋含义相近的表达')
    card(s, 330, 157, 226, 96, '② 连证据', '药物—机制—来源\n放到同一张关系图里', GREEN, GREEN_PALE)
    arrow(s, (286, 202), (324, 202))
    arrow(s, (443, 254), (443, 292), GREEN)
    card(s, 330, 299, 226, 96, '③ 核对用途', '人群、给药途径\n与用户预测目标', GOLD, GOLD_PALE)
    card(s, 54, 299, 226, 96, '④ 给出建议', '组件＋引用＋缺口\n每项都能查回来源')
    arrow(s, (324, 344), (286, 344), GOLD)
    label(s, '没有合格资料支持的地方，明确保留为缺口', 54, 410, 502)
    words(s, [
        ('先找到相关内容', '既按关键词找，也按意思找；关系图把药物、机制和来源关联起来，帮助判断资料讲的是什么。'),
        ('再判断能否使用', '检查条件和引用后，才生成建议。资料没写清楚的地方，不能自动当作已经获得支持。'),
    ], '不是让模型凭印象选机制，而是让每条建议带着适用条件和证据。')
    pages.append(s)
    assert len(pages) == 2
    return pages


def make_component_technical_slides():
    pages = []
    s = teaching_slide(
        '技术补充：文字匹配与图关系一起筛选证据',
        '先广泛检索，再根据文字和图关系重新排序，筛选符合当前用途的证据。',
        '组件推荐 / 技术补充 1')
    card(s, 55, 151, 502, 71, '关键词＋五种语义编码', '每路召回 50 个子图 → 按排名融合为 100 个')
    arrow(s, (307, 225), (307, 242))
    s.line([(176, 246), (437, 246)], TEAL, 1.3)
    arrow(s, (176, 246), (176, 259))
    arrow(s, (437, 246), (437, 259), GREEN)
    card(s, 55, 264, 242, 96, '文本重新排序', 'Qwen3-Reranker\n0.6B')
    card(s, 316, 264, 241, 96, '图关系匹配', '2 层、4 个注意力头\n每个向量 256 维', GREEN, GREEN_PALE)
    arrow(s, (176, 364), (245, 376))
    arrow(s, (437, 364), (365, 376), GREEN)
    card(s, 94, 380, 424, 47, '核对条件、减少重复 → 最多 8 个子图')
    words(s, [
        ('HGT 是什么', '一种图神经网络，区分节点和关系类型。两层逐步传递信息，四个注意力头并行关注不同信息。'),
        ('语义编码是什么', '把文字变成可比较的数字向量。五种编码包括 Qwen3-Embedding-0.6B；图匹配还使用当前请求的信息。'),
    ], '正式图匹配还含教师与残差机制，因此不能把所有收益都单独归因于 HGT。')
    pages.append(s)

    s = teaching_slide(
        '技术补充：把证据图接到语言模型上',
        '软提示是向量，不是句子；带编号的证据文本仍一起提供，方便生成后核验。',
        '组件推荐 / 技术补充 2')
    eq(s, r'\mathbf{g}=\sum_i a_i\mathbf{h}_i', 151, h=47)
    label(s, 'h_i：单个子图；a_i：汇聚权重；g：全局向量', 55, 208, 502, size=16)
    arrow(s, (307, 244), (307, 258))
    card(s, 81, 265, 452, 73, '共享投影器：256 → 2048 → 4096', '把图向量变成语言模型能接收的向量')
    arrow(s, (307, 341), (307, 355))
    card(s, 52, 365, 309, 63, '1 个全局＋最多 8 个局部提示')
    label(s, '＋', 363, 382, 25, TEAL, 21)
    card(s, 393, 365, 175, 63, '编号证据文本', color=GOLD, fill=GOLD_PALE)
    words(s, [
        ('哪些部分参与训练', '先训练图匹配；提示阶段固定图编码器，只更新汇聚和投影器。投影器就是连接两种表示的小网络。'),
        ('语言模型负责什么', '主实验的 Qwen3-8B 权重冻结，根据证据选择组件和引用。程序继续核验合法编号、条件、参数和单位。'),
    ], '语言模型负责有依据地组织建议，原文支持程度仍需要结合具体用途判断。')
    pages.append(s)
    assert len(pages) == 2
    return pages
