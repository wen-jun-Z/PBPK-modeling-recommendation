"""Bounded native Qwen thinking followed by source-bound constrained JSON.

Both phases continue one assistant turn over the exact original prompt tokens.
An artificial closing think delimiter after a budget/EOS stop is disclosed;
only tokens actually generated by the model are recorded as reasoning. Syntax
and a reasoning trace do not establish the truth or support of a judgment.
"""
from __future__ import annotations

import fcntl
import hashlib
import json
import os
from pathlib import Path
import shutil
import time
import uuid

import frontier_modern_judge as modern
from frontier_conditional_citation_decoding import conditional_citation_constraint, decoding_protocol

ROOT = modern.ROOT
VERSION = "pbpk-native-qwen-thinking-conditional-json-v1"
THINKING_TOKENS = 1024
MAX_INPUT_TOKENS = 12000
MAX_BATCH_TOKENS = 32000
MAX_JOURNAL_BYTES = 4 * 1024**3
THINK_END_ID = 248069
OFFICIAL_EOS = [248046, 248044]
SEPARATOR_IDS = [271]  # Official tokenizer's \n\n after </think>.


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"), allow_nan=False)


def sha(value):
    return hashlib.sha256(value if isinstance(value, bytes) else value.encode()).hexdigest()


def split_reasoning_tokens(tokens, think_end_id, official_eos, pad_token_id, budget=THINKING_TOKENS):
    """Find each row's first actual stop BEFORE removing padded batch suffixes."""
    tokens = list(tokens)
    if type(budget) is not int or budget < 1 or any(type(t) is not int for t in tokens):
        raise ValueError("Invalid reasoning token sequence or budget")
    stop_ids = set(official_eos) | {think_end_id}
    position = next((i for i, token in enumerate(tokens) if token in stop_ids), None)
    if position is not None:
        if position >= budget or any(t != pad_token_id for t in tokens[position + 1:]):
            raise ValueError("Unexpected tokens beyond a row's reasoning stop")
        raw, analysis = tokens[:position + 1], tokens[:position]
        stop = tokens[position]
        reason = "think_end" if stop == think_end_id else "official_eos"
    else:
        if len(tokens) > budget:
            raise ValueError("Reasoning exceeded its declared generation budget")
        raw, analysis, stop = tokens, tokens, None
        reason = "budget_exhausted" if len(tokens) == budget else "unexpected_early_stop"
    return {"raw_token_ids": raw, "analysis_token_ids": analysis,
        "stop_reason": reason, "stop_token_id": stop,
        "native_thinking_completed": reason == "think_end",
        "budget_exhausted": reason == "budget_exhausted",
        "forced_think_closure": reason != "think_end",
        "generated_token_count": len(raw), "analysis_token_count": len(analysis),
        "padding_tokens_discarded": len(tokens) - len(raw)}


def continuation_tokens(prompt_ids, reasoning_record, think_end_id, separator_ids):
    """Append actual analysis and only a structural boundary; never rewrite it."""
    return list(prompt_ids) + list(reasoning_record["analysis_token_ids"]) + [think_end_id] + list(separator_ids)


def pad_token_rows(rows, pad_token_id, torch):
    if not rows or any(not row for row in rows):
        raise ValueError("Cannot pad empty prompt rows")
    width = max(map(len, rows))
    if width > MAX_INPUT_TOKENS:
        raise ValueError("Complete prompt exceeds 12000 tokens; truncation refused")
    return {"input_ids": torch.tensor([[pad_token_id] * (width-len(row)) + list(row) for row in rows], dtype=torch.long),
        "attention_mask": torch.tensor([[0] * (width-len(row)) + [1] * len(row) for row in rows], dtype=torch.long)}


def _official_artifacts(weights):
    directory = Path(weights["path"])
    if not directory.resolve().is_relative_to(ROOT):
        raise ValueError("Unscoped Qwen tokenizer artifacts")
    result = {}
    for name in ("chat_template.jinja", "tokenizer_config.json", "generation_config.json", "README.md"):
        path = directory / name
        if not path.resolve().is_relative_to(ROOT) or modern.digest(path) != weights["sha256"][name]:
            raise ValueError("Pinned official thinking artifact changed")
        result[name] = weights["sha256"][name]
    return result


def generation_protocol(weights=None):
    """Freeze beside the runner's prompt/source protocol before any generation."""
    weights = weights or json.loads(modern.WEIGHTS.read_text())
    if weights.get("repo") != modern.REPO or weights.get("revision") != modern.REVISION:
        raise ValueError("Reasoning protocol requires the same pinned Qwen revision")
    return {"version": VERSION, "implementation_sha256": modern.digest(Path(__file__)),
        "parent_backend_sha256": modern.digest(Path(modern.__file__)),
        "repo": modern.REPO, "revision": modern.REVISION,
        "official_artifact_sha256": _official_artifacts(weights),
        "phase1": {"enable_thinking": True, "max_new_tokens": THINKING_TOKENS,
            "do_sample": False, "json_constraint": False, "per_row_stop_ids": [THINK_END_ID, *OFFICIAL_EOS],
            "stop_implementation": "Transformers native EOS criteria and per-row unfinished-sequence padding",
            "sampling_disclosure": "Greedy bounded experimental thinking; not official recommended sampling or unrestricted thinking benchmark"},
        "phase2": {"continuation": "Exact unpadded original input IDs + generated analysis IDs + </think> + official newline separator",
            "max_new_tokens": 96, "repair_max_new_tokens": 160, "do_sample": False,
            "official_eos_ids": OFFICIAL_EOS, "conditional_decoding": decoding_protocol()},
        "forced_closure": "At budget exhaustion or official EOS before </think>, append only the structural </think> delimiter; mark forced_think_closure and the actual stop reason",
        "repair": "Same two-phase generation with unchanged source/query and the existing failed-output/validation feedback messages",
        "source_policy": "Analysis is model output, never an additional source, citation, gold label, or posthoc answer correction",
        "input_limit": MAX_INPUT_TOKENS, "input_truncation": False,
        "batch_token_budget": MAX_BATCH_TOKENS, "batch_plan_includes": "original padded input + 1024 thinking + closure/separator + up to 160 final tokens",
        "gpu_memory_cap_gib": 36, "maximum_prompt_batch_size": 16,
        "journal": {"format": "append-only source-bound phase records; metrics reference byte offsets and SHA256",
            "relative_path_in_assessment": "reasoning/qwen_generation_journal.jsonl", "max_bytes": MAX_JOURNAL_BYTES,
            "phase1_written_before_phase2": True, "records_preserved_on_second_phase_failure": True},
        "scientific_accuracy_verified": False, "semantic_entailment_verified": False}


class ReasonedGPUJudge(modern.ModernGPUJudge):
    def __init__(self, weights, memory_gib=36, loading_callback=None):
        if memory_gib != 36:
            raise ValueError("Reasoned judge uses the frozen 36 GiB allocator cap")
        _official_artifacts(weights)
        super().__init__(weights, memory_gib, loading_callback)
        self.device = "cuda:0"
        self.reasoning_tokens = THINKING_TOKENS
        self.think_end_id = THINK_END_ID
        self.official_eos = list(OFFICIAL_EOS)
        self.separator_ids = list(SEPARATOR_IDS)
        if (self.tokenizer.encode("</think>", add_special_tokens=False) != [self.think_end_id] or
                self.tokenizer.encode("\n\n", add_special_tokens=False) != self.separator_ids or
                list(self.model.generation_config.eos_token_id) != self.official_eos):
            raise ValueError("Official Qwen thinking delimiter or EOS contract changed")
        probe = self.tokenizer.apply_chat_template([
            {"role": "system", "content": "Protocol verification."},
            {"role": "user", "content": "Verify the template."}],
            tokenize=False, add_generation_prompt=True, enable_thinking=True)
        if not probe.endswith("<|im_start|>assistant\n<think>\n"):
            raise ValueError("Qwen template did not open the native thinking channel")
        self.json_constraint = conditional_citation_constraint(self.json_constraint)
        self.metadata.update(backend="native_qwen_two_phase_thinking", enable_thinking=True,
            decoding="unconstrained_thinking_then_conditional_json", thinking_max_new_tokens=THINKING_TOKENS,
            reasoning_protocol=generation_protocol(weights), max_complete_input_tokens=MAX_INPUT_TOKENS)

    def _render(self, packet, queries, repair=None):
        return self.tokenizer.apply_chat_template(self._messages(packet, queries, repair),
            tokenize=False, add_generation_prompt=True, enable_thinking=True)

    def select_batch_size(self, tasks, maximum):
        possible = tasks[:min(maximum, self.prompt_batch_limit)]
        if not possible:
            raise ValueError("Cannot plan an empty reasoning batch")
        lengths = [len(self.tokenizer.encode(self._render(p, qs), add_special_tokens=False)) for p, qs in possible]
        width, selected = 0, 0
        for count, length in enumerate(lengths, 1):
            if length > MAX_INPUT_TOKENS:
                raise ValueError("Complete prompt exceeds 12000 tokens; truncation refused")
            width = max(width, length)
            if (width + self.reasoning_tokens + 1 + len(self.separator_ids) + 160) * count > self.batch_token_budget:
                break
            selected = count
        return max(1, selected)

    def _run_stage(self, rows, max_new_tokens, eos, constraint=None):
        inputs = {key: value.to(self.device) for key, value in
                  pad_token_rows(rows, self.tokenizer.pad_token_id, self.torch).items()}
        width = inputs["input_ids"].shape[1]
        if self.device.startswith("cuda"):
            self.torch.cuda.synchronize()
        started = time.monotonic()
        kwargs = {"max_new_tokens": max_new_tokens, "do_sample": False, "use_cache": True,
            "temperature": None, "top_p": None, "top_k": None,
            "pad_token_id": self.tokenizer.pad_token_id, "eos_token_id": eos}
        if constraint is not None:
            kwargs["prefix_allowed_tokens_fn"] = constraint
        with self.torch.inference_mode():
            outputs = self.model.generate(**inputs, **kwargs)
        if self.device.startswith("cuda"):
            self.torch.cuda.synchronize()
        seconds = time.monotonic() - started
        if (outputs.ndim != 2 or outputs.shape[0] != len(rows) or
                not width <= outputs.shape[1] <= width + max_new_tokens or
                not self.torch.equal(outputs[:, :width], inputs["input_ids"])):
            raise ValueError("Generation changed cardinality, token budget or original prompt tokens")
        generated = outputs[:, width:].detach().cpu().tolist()
        result = {"wall_seconds": seconds, "input_token_width": width,
            "input_tokens_per_prompt": [len(row) for row in rows], "output_token_width": outputs.shape[1] - width}
        del inputs, outputs
        return generated, result

    def _context(self, tasks, texts, rows, repairs):
        import run_frontier_assessment as assessment
        folder = Path(assessment.ASSESS)
        if not folder.resolve().is_relative_to(ROOT):
            raise ValueError("Reasoning artifacts outside the project")
        protocol = folder / "judge_protocol.json"
        if not protocol.is_file() or not protocol.resolve().is_relative_to(ROOT):
            raise ValueError("Freeze the scoped judge protocol before reasoning")
        task_records = []
        for i, ((packet, queries), text, ids) in enumerate(zip(tasks, texts, rows)):
            repair = repairs[i] if repairs is not None else None
            task_records.append({"batch_index": i, "packet_sha256": packet["packet_sha256"],
                "packet_body_sha256": sha(canonical(packet["body"])), "source_refs_sha256": sha(canonical(packet["refs"])),
                "query_ids": [q.get("query_id") for q in queries], "query_text_sha256": [sha(q["text"]) for q in queries],
                "rendered_prompt_sha256": sha(text), "input_token_ids_sha256": sha(canonical(ids)),
                "repair": repair is not None, "repair_payload_sha256": sha(canonical(repair)) if repair is not None else None})
        return folder, {"version": VERSION, "attempt_id": uuid.uuid4().hex,
            "model_repo": self.weights["repo"], "model_revision": self.weights["revision"],
            "judge_protocol_sha256": modern.digest(protocol), "system_prompt_sha256": sha(assessment.SYSTEM),
            "source_policy": "Model analysis is not source evidence", "tasks": task_records}

    @staticmethod
    def _append_artifact(folder, record):
        path = folder / "reasoning/qwen_generation_journal.jsonl"
        if not path.resolve().is_relative_to(ROOT):
            raise ValueError("Unscoped reasoning journal")
        path.parent.mkdir(parents=True, exist_ok=True)
        data = (canonical(record) + "\n").encode()
        if shutil.disk_usage(ROOT).free < 30 * 1024**3:
            raise RuntimeError("Insufficient project disk headroom for reasoning journal")
        with path.open("a+b") as handle:
            fcntl.flock(handle, fcntl.LOCK_EX)
            handle.seek(0, os.SEEK_END)
            offset = handle.tell()
            if offset:
                handle.seek(-1, os.SEEK_END)
                if handle.read(1) != b"\n":
                    raise ValueError("Uncommitted reasoning journal tail; preserving it without append")
            if offset + len(data) > MAX_JOURNAL_BYTES:
                raise RuntimeError("Reasoning journal reached its 4 GiB output guard")
            handle.seek(0, os.SEEK_END)
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        return {"path": str(path.relative_to(ROOT)), "offset": offset, "length": len(data),
            "sha256": sha(data), "task_count": len(record["tasks"]), "attempt_id": record["attempt_id"], "phase": record["phase"]}

    def generate(self, tasks, max_new_tokens=96, repairs=None):
        if not tasks or repairs is not None and len(repairs) != len(tasks):
            raise ValueError("Empty generation batch or repair cardinality mismatch")
        if len(tasks) > self.prompt_batch_limit:
            raise ValueError("Reasoning batch exceeds the frozen prompt-count limit")
        if type(max_new_tokens) is not int or not 1 <= max_new_tokens <= 160:
            raise ValueError("Final generation budget must be within the frozen 160-token maximum")
        texts = [self._render(p, qs, repairs[i] if repairs is not None else None) for i, (p, qs) in enumerate(tasks)]
        rows = [self.tokenizer.encode(text, add_special_tokens=False) for text in texts]
        if not all(rows) or max(map(len, rows)) > MAX_INPUT_TOKENS:
            raise ValueError("Empty or over-budget complete prompt; truncation refused")
        planned = max(map(len, rows)) + self.reasoning_tokens + 1 + len(self.separator_ids) + max_new_tokens
        if planned * len(tasks) > self.batch_token_budget:
            raise ValueError("Reasoning plus final-answer batch exceeds declared token budget")
        folder, context = self._context(tasks, texts, rows, repairs)
        started = time.monotonic()
        raw, thinking_metrics = self._run_stage(rows, self.reasoning_tokens, [self.think_end_id, *self.official_eos])
        thinking = [split_reasoning_tokens(tokens, self.think_end_id, self.official_eos,
                    self.tokenizer.pad_token_id, self.reasoning_tokens) for tokens in raw]
        for record in thinking:
            record["raw_text"] = self.tokenizer.decode(record["raw_token_ids"], skip_special_tokens=False)
        # The analysis IDs are exactly raw IDs before the recorded terminal.
        # Do not persist that nearly identical list or a duplicate text field.
        stored_thinking = [{key: value for key, value in record.items() if key != "analysis_token_ids"}
                           for record in thinking]
        thinking_ref = self._append_artifact(folder, {**context, "phase": "thinking", "at": modern.now(),
            "max_new_tokens": self.reasoning_tokens, "metrics": thinking_metrics, "reasoning": stored_thinking})
        if any(record["stop_reason"] == "unexpected_early_stop" for record in thinking):
            raise ValueError("Thinking stopped early without an official stop; raw output preserved")
        final_rows = [continuation_tokens(ids, record, self.think_end_id, self.separator_ids) for ids, record in zip(rows, thinking)]
        try:
            final_tokens, final_metrics = self._run_stage(final_rows, max_new_tokens, self.official_eos,
                                                        self.json_constraint.for_tasks(tasks))
        except BaseException as error:
            self._append_artifact(folder, {**context, "phase": "answer_error", "at": modern.now(),
                "reasoning_artifact": thinking_ref, "error_type": type(error).__name__})
            raise
        values = self.tokenizer.batch_decode(final_tokens, skip_special_tokens=True)
        if len(values) != len(tasks):
            raise ValueError("Final answer count differs from original task count")
        final_ref = self._append_artifact(folder, {**context, "phase": "answer", "at": modern.now(),
            "reasoning_artifact": thinking_ref, "max_new_tokens": max_new_tokens,
            "final_input_token_ids_sha256": [sha(canonical(ids)) for ids in final_rows],
            "metrics": final_metrics, "raw_output_token_ids": final_tokens, "outputs": values})
        metrics = {**thinking_metrics, "wall_seconds": thinking_metrics["wall_seconds"] + final_metrics["wall_seconds"],
            "end_to_end_wall_seconds": time.monotonic() - started,
            "thinking_wall_seconds": thinking_metrics["wall_seconds"], "answer_wall_seconds": final_metrics["wall_seconds"],
            "output_token_width": final_metrics["output_token_width"],
            "answer_input_token_width": final_metrics["input_token_width"],
            "prompt_batch_size": len(tasks), "requests_per_prompt": [len(qs) for _, qs in tasks],
            "thinking_token_counts": [r["generated_token_count"] for r in thinking],
            "thinking_stop_reasons": [r["stop_reason"] for r in thinking],
            "thinking_budget_exhausted": [r["budget_exhausted"] for r in thinking],
            "forced_think_closure": [r["forced_think_closure"] for r in thinking],
            "reasoning_artifact": thinking_ref, "final_artifact": final_ref,
            "gpu_memory_cap_gib": self.memory_cap_gib, "prompt_batch_limit": self.prompt_batch_limit,
            "batch_token_budget": self.batch_token_budget, "capacity_upgrade_at": None,
            "enable_thinking": True, "reasoning_backend_version": VERSION,
            "cuda_peak_allocated_bytes": self.torch.cuda.max_memory_allocated(0) if self.device.startswith("cuda") else None,
            "cuda_peak_reserved_bytes": self.torch.cuda.max_memory_reserved(0) if self.device.startswith("cuda") else None}
        return values, metrics
