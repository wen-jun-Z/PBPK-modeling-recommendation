#!/usr/bin/env python3
"""Update manuscript Tables 10/11 from the single current blueprint manifest.

The legacy renderers and frozen experiments are read-only dependencies. Table 10
uses already locked native and clinical-protocol predictions. Table 11 performs
nine new native predictions from the exact current Treprostinil mapping, without
refitting or assigning clinical observations to hypothetical inputs.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import csv
import json
from pathlib import Path

import numpy as np

import render_current_clinical_table as clinical
import render_ten_drug_table as scenarios
from pbpk_kb.blueprints.evidence_blueprint import EvidenceBlueprintRequest
from pbpk_kb.blueprints.source_workflow import inside, save, sha256


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'results/data/blueprint_current.json'
METHOD = 'evidence_first_unified_blueprint'


def read(path):
    return json.loads(inside(path, ROOT, exists=True).read_text())


def rel(path):
    return str(inside(path, ROOT, exists=True).relative_to(ROOT))


def source(record):
    if not isinstance(record, dict) or set(('path', 'sha256')) - record.keys():
        raise ValueError('Manifest artifact must supply path and SHA256')
    path = inside(record['path'], ROOT, exists=True)
    if sha256(path) != record['sha256']:
        raise ValueError('Current artifact checksum changed: ' + record['path'])
    return path


def selected_context(manifest_path):
    document = read(manifest_path)
    records = document['cases']
    if isinstance(records, dict):
        records = [dict(record, case_id=cid) for cid, record in records.items()]
    if len(records) != 10 or len({c['case_id'] for c in records}) != 10:
        raise ValueError('The current method manifest must contain all ten drugs')
    case = next(c for c in records if c['case_id'] == scenarios.CASE_ID)
    run_summary = source(document['run_summary'])
    return document, case, run_summary


def render_clinical(manifest_path):
    document, _, run_summary = selected_context(manifest_path)
    comparison_path = source(document['comparison_input'])
    if comparison_path.parent / 'summary.json' != run_summary:
        raise ValueError('Clinical comparison and run summary must belong to the same current run')
    summary = read(run_summary)
    if len(summary.get('protocol', {}).get('cases', [])) != 10:
        raise ValueError('Current summary must retain the ten clinical protocol cases')
    native_refs = {c['case_id']: c for c in document['cases']}
    comparison = read(comparison_path)
    for case in comparison['cases']:
        expected = source(native_refs[case['case_id']]['target_prediction'])
        reported = read(source(case['predictions']['ours']))
        if source(reported['native_source']) != expected:
            raise ValueError('Table 10 would use a different current native prediction: ' + case['case_id'])
    clinical.build(comparison_path)
    tex = clinical.DEST / 'blueprint_clinical_metrics.tex'
    text = tex.read_text().replace('Optimized Ours:', 'Current unified blueprint:')
    text = text.replace('% Generated by scripts/render_current_clinical_table.py; optimized Ours only.',
                        '% Generated via scripts/render_unified_blueprint_tables.py; current unified method.')
    text = text.replace(r'\textbf{Values.}',
                        r'\textbf{Method.} The same evidence-first construction and bounded two-parameter development fitting policy is applied to all ten drugs; qualified independent inputs take priority and missing inputs retain RF priors. \textbf{Values.}')
    tex.write_text(text)
    csv_path = clinical.DEST / 'blueprint_clinical_metrics.csv'
    with csv_path.open(newline='') as handle:
        reader = csv.DictReader(handle)
        fields, rows = reader.fieldnames, list(reader)
    for row in rows:
        row['method'] = METHOD
    with csv_path.open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader(); writer.writerows(rows)
    path = clinical.DEST / 'blueprint_clinical_audit.json'
    audit = read(path)
    audit.update(method=METHOD, current_manifest={'path': rel(manifest_path), 'sha256': sha256(manifest_path)},
                 renderer_adapter={'path': rel(Path(__file__)), 'sha256': sha256(Path(__file__))})
    audit['source_sha256'].update({rel(manifest_path): sha256(manifest_path), rel(Path(__file__)): sha256(Path(__file__))})
    audit['output_sha256'] = {rel(p): sha256(p) for p in (tex, csv_path)}
    save(path, audit)


def scenario_context(manifest_path):
    document, case, run_summary = selected_context(manifest_path)
    mapping_path = source(case['mapping'])
    request_path = source(case['target_request'])
    source(case['target_prediction'])
    mapping, reference = read(mapping_path), read(request_path)
    if (not mapping.get('eligible') or mapping.get('algorithm_version') != 'curve-pattern-input-prior-1.0'
            or reference['compound_name'] != 'Treprostinil'):
        raise ValueError('Expected the eligible current Treprostinil blueprint mapping')
    if mapping.get('construction_partition_method') != reference['partition_method']:
        raise ValueError('Current mapping and native target request partition formulas disagree')
    # No manifest snapshots or copies of old predictions are made. These exact
    # referenced artifacts, not the mutable presentation manifest, are locked.
    data = run_summary.parent / 'input_response'
    scenarios.DATA = data
    scenarios.SOURCE = run_summary.parent
    return document, case, mapping_path, request_path, mapping, reference, data


def prepare_scenarios(manifest_path):
    document, case, mapping_path, request_path, mapping, reference, data = scenario_context(manifest_path)
    if data.exists():
        raise FileExistsError('Existing current input-response run is immutable; render or inspect it')
    pins = {rel(mapping_path): sha256(mapping_path), rel(request_path): sha256(request_path),
            rel(Path(__file__)): sha256(Path(__file__)),
            rel(Path(scenarios.__file__)): sha256(Path(scenarios.__file__))}
    pins[case['target_prediction']['path']] = case['target_prediction']['sha256']
    for record in (reference['evidence_ledger'], mapping['training_source'],
                   *[e['source'] for e in reference['evidence']]):
        path = source(record)
        pins[rel(path)] = record['sha256']
    for name in ('development_curve_blueprint', 'curve_pattern_blueprint', 'pk_anchored_blueprint',
                 'pk_anchor_moments', 'evidence_blueprint', 'extended_prediction',
                 'endpoint_prediction', 'evidence_native_audit', 'design_runtime'):
        path = ROOT / f'src/pbpk_kb/blueprints/{name}.py'
        pins[rel(path)] = sha256(path)
    if reference['target'].get('window_end_h') not in (None, 9.):
        raise ValueError('The retained Table 11 endpoint labels require the 0–9 h request window')
    cases = []
    for multiplier, label in ((.5, 'd0p5'), (1., 'd1'), (2., 'd2')):
        for condition in ('C1', 'C2', 'C3'):
            req = deepcopy(reference)
            req['dosing']['dose_mg'] = reference['dosing']['dose_mg'] * multiplier
            if condition == 'C2':
                req['dosing']['infusion_minutes'] *= 2.
            if condition == 'C3':
                req['human'].update(sex='FEMALE', age_years=30., weight_kg=60., height_cm=165.)
                req['assumptions'] = [a for a in req['assumptions']
                    if not any(token in a.lower() for token in ('male', '175 cm', '175cm', '69.5 kg', '69.5kg'))]
                req['assumptions'].append('Hypothetical female adult: 30 years, 60 kg and 165 cm; not a measured study subject.')
            req['assumptions'] += ['Input-response demonstration only; no clinical observations or error scores assigned.',
                'Absolute dose is held fixed across the three input conditions at each dose level.',
                'The current drug mapping is reused unchanged without any refitting.']
            req = EvidenceBlueprintRequest.model_validate(req).model_dump(mode='json', exclude_none=True)
            cases.append({'case_id': f'treprostinil_{label}_{condition}', 'dose_multiplier': multiplier,
                          'condition': condition, 'request': req,
                          'repeats_clinical_representative_input': multiplier == 1. and condition == 'C1'})
    # Explicitly preserve the published demonstration design. Changing the
    # current target physiology requires reviewing labels, not silent relabeling.
    human, dose = reference['human'], reference['dosing']
    if (human['sex'], human['age_years'], human['weight_kg'], human['height_cm'],
            dose['dose_mg'], dose['infusion_minutes']) != ('MALE', 30., 69.5, 175., .06255, 60.):
        raise ValueError('Current target inputs differ from the retained Table 11 demonstration')
    scenarios.verify(pins)
    data.mkdir()
    protocol = {'version': 'unified-one-drug-input-response-1.0', 'created_at': scenarios.now(),
        'method': METHOD, 'compound': 'Treprostinil', 'mapping_path': rel(mapping_path),
        'mapping_sha256': sha256(mapping_path), 'source_summary': document['run_summary']['path'],
        'current_manifest_at_launch': {'path': rel(manifest_path), 'sha256': sha256(manifest_path)},
        'partition_method': reference['partition_method'], 'mapping_algorithm': mapping['algorithm_version'],
        'source_case_id': scenarios.CASE_ID, 'cases': cases, 'input_pins': pins, 'native_prediction_count': 9,
        'generator_sha256_at_launch': sha256(Path(__file__)), 'parameters_refitted': False,
        'clinical_observations_used': False,
        'interpretation': 'Prediction-only input response, not an additional clinical validation dataset',
        'notes': ['C1 age, sex and height are representative assumptions; weight is the source study mean.',
                  'C2 doubles infusion duration at the same total dose, halving the infusion rate.',
                  'C3 changes sex, weight and height together; it does not isolate a causal sex effect.',
                  'The 1x C1 representative input adds no clinical sample.']}
    save(data / 'protocol.json', protocol)
    return protocol


def run_scenarios(manifest_path, workers):
    # Inject only the preparation adapter. The old execution function remains
    # unchanged and performs all nine fresh native simulations and source checks.
    original = scenarios.prepare
    scenarios.prepare = lambda: prepare_scenarios(manifest_path)
    try:
        scenarios.run_native(workers)
    finally:
        scenarios.prepare = original


def render_scenarios(manifest_path):
    _, source_case, mapping_path, _, mapping, reference, data = scenario_context(manifest_path)
    protocol = read(data / 'protocol.json')
    if protocol['mapping_path'] != rel(mapping_path) or protocol['mapping_sha256'] != sha256(mapping_path):
        raise ValueError('Table 11 scenarios were not predicted by the current mapping')
    summary = read(data / 'summary.json')
    if len(summary['results']) != 9:
        raise ValueError('All nine prediction attempts must finish before reporting')
    repeated = summary['results']['treprostinil_d1_C1']
    if repeated['status'] != 'predicted':
        raise ValueError('The repeated current clinical input failed native prediction')
    repeated_path = ROOT / repeated['output_dir'] / 'prediction_locked.json'
    actual, expected = read(repeated_path), read(source(source_case['target_prediction']))
    if actual['time_unit'] != expected['time_unit'] or actual['unit'] != expected['unit']:
        raise ValueError('Repeated current clinical input has inconsistent curve units')
    for name in ('time_min', 'concentration'):
        if len(actual[name]) != len(expected[name]) or not np.allclose(actual[name], expected[name], rtol=1e-8, atol=1e-12):
            raise ValueError('Table 11 reference input does not reproduce the current target prediction: ' + name)
    max_difference = float(np.max(np.abs(np.asarray(actual['concentration']) - expected['concentration'])))
    scenarios.render()
    tex = scenarios.DEST / 'blueprint_ten_drug.tex'
    text = tex.read_text()
    formula = {'RodgersRowland': 'Rodgers--Rowland', 'PKSimStandard': 'PK-Sim Standard'}[reference['partition_method']]
    text = text.replace('Locked optimized blueprint; Rodgers--Rowland', 'Current unified blueprint; ' + formula)
    horizons = set()
    for result in summary['results'].values():
        if result['status'] == 'predicted':
            curve = read(ROOT / result['output_dir'] / 'prediction_locked.json')
            horizons.add(curve['time_min'][-1] / 60.)
    if len(horizons) != 1:
        raise ValueError('Table 11 needs an explicit note for unequal prediction horizons')
    text = text.replace('simulated to 1344 h', f'simulated to {next(iter(horizons)):g} h')
    tex.write_text(text)
    audit_path = scenarios.DEST / 'blueprint_ten_drug_audit.json'
    audit = read(audit_path)
    audit.update(method=METHOD, current_manifest={'path': rel(manifest_path), 'sha256': sha256(manifest_path)},
                 mapping_path=rel(mapping_path), partition_method=reference['partition_method'],
                 renderer_adapter={'path': rel(Path(__file__)), 'sha256': sha256(Path(__file__))},
                 output_sha256=sha256(tex), simulated_horizon_h=next(iter(horizons)),
                 repeated_target_curve_check={'status': 'passed', 'reference': source_case['target_prediction'],
                     'scenario_path': rel(repeated_path), 'scenario_sha256': sha256(repeated_path),
                     'max_absolute_difference_umol_l': max_difference})
    save(audit_path, audit)
    summary = read(data / 'summary.json')
    summary['table_sha256'] = sha256(tex)
    save(data / 'summary.json', summary)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, default=MANIFEST)
    parser.add_argument('--run-scenarios', action='store_true', help='Run nine new native predictions before rendering')
    parser.add_argument('--table', choices=('10', '11', 'both'), default='both')
    parser.add_argument('--workers', type=int, choices=range(1, 7), default=3)
    args = parser.parse_args()
    if args.run_scenarios:
        if args.table == '10':
            parser.error('--run-scenarios requires table 11')
        run_scenarios(args.manifest, args.workers)
    if args.table in ('10', 'both'):
        render_clinical(args.manifest)
    if args.table in ('11', 'both'):
        render_scenarios(args.manifest)


if __name__ == '__main__':
    main()
